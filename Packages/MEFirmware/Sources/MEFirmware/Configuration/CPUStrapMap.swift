import Foundation

/// The CPU strap message of the **MIP table** — the bits Flash Image Tool writes
/// into the `descriptor:CPU` container of its `MipDescNvar`, and what a CSME 18
/// image keeps in the FITC partition's `smip` file.
///
/// The message itself is the same idea as the descriptor's MIP CPU straps of
/// Tiger Point through CSME 16 (a few 32-bit words, the last one's high half a
/// CRC-16), but its place moved: on CSME 18 the descriptor's MIP area is not
/// where it is kept. The FITC partitition's payload is a record table, and one
/// record — the `SmipTable` nvar, FileID `0x10023E00` on the dump at hand — is a
/// **MIP descriptor**:
///
///     u16 NumberOfDescriptors
///     u16 SizeOfMip
///     { u16 BlockType, u16 BlockOffset, u16 BlockLength, u16 Reserved }[N]
///
/// The first block (type 1, the `PmcAndCpu` container) carries the PMC straps,
/// then, at offset 0x48, the CPU message header — `Reserved_15_0`,
/// `Interpretation_Num` (bit 16), `Reserved_23_17` and `CPU_Strap_Length`
/// (bits 24–31) — and at 0x4C the message itself, `CPU_Strap_Length` words.
/// The tool lays the message's fields out in its `CPU_smip` document; this
/// map is that document for the generation, generated by
/// `Skills/me-eom-structures/scripts/strap18_map.py`.
///
/// Verified on the CSME 18 dump at hand (HP EliteBook 630 13.3 inch G11,
/// 18.0.10.2288): `CPU_Strap_Length` 3, the three words
/// `0x00801000 0x04002000 0xD6CE0000`, the stored CRC-16 `0xD6CE` equal to
/// CCITT-FALSE over the last two words with the CRC field zeroed, and the
/// decoded fields agreeing with the tool's own interface (All Cores Active,
/// hyperthreading not disabled, IA/GT/SA VR addresses 0/1/2 — Meteor Lake has
/// no hyperthreading and the strap is for debugging).
public struct CPUStrapMap: Sendable {
    /// One field of the message, as the tool's `serialized_item` places it: a
    /// byte offset, the bit the field starts at in the little-endian dword
    /// there, and how many bits it takes.
    public struct Field: Sendable, Equatable {
        public var name: String
        public var offset: Int
        public var bit: Int
        public var count: Int
        /// The tool's own name for it ("Disable Hyperthreading"), where it has
        /// one; the raw bits carry their identifier alone.
        public var label: String?
        /// How the tool's interface groups it (`CpuStraps`).
        public var section: String?
        /// What the tool's panel says about it.
        public var help: String?
        /// The tool's words for an enumerated value (0 "No", 1 "Yes"; the
        /// core counts), where it enumerates one.
        public var options: [Int: String]?

        public init(name: String, offset: Int, bit: Int, count: Int,
                    label: String? = nil, section: String? = nil,
                    help: String? = nil, options: [Int: String]? = nil) {
            self.name = name
            self.offset = offset
            self.bit = bit
            self.count = count
            self.label = label
            self.section = section
            self.help = help
            self.options = options
        }
    }

    public var name: String
    public var fields: [Field]

    public init(name: String, fields: [Field]) {
        self.name = name
        self.fields = fields
    }

    /// The layout for a generation's major number, or nil where its CPU straps
    /// are not kept this way — every generation before CSME 18 keeps them in
    /// the descriptor's own MIP area, read through `StrapMap`.
    public static func forME(major: Int) -> CPUStrapMap? {
        major == 18 ? .csme18 : nil
    }

    public static var all: [CPUStrapMap] { [.csme18] }
}

/// One strap of the message as an image holds it.
public struct CPUStrapReading: Codable, Sendable, Equatable {
    public var name: String
    public var value: Int

    public init(name: String, value: Int) {
        self.name = name
        self.value = value
    }
}

/// The CPU straps a CSME 18 image's MIP table holds.
public struct CPUStrapReadings: Codable, Sendable, Equatable {
    /// The fields of `CPUStrapMap`, in the map's order.
    public var readings: [CPUStrapReading]
    /// The message's length, from the header's `CPU_Strap_Length`.
    public var messageLengthWords: Int
    /// The CRC-16 the message stores, and whether it is the one the message
    /// computes — all-zero on some builds, which is a value, not a pass.
    public var crcStored: Int
    public var crcValid: Bool

    public init(readings: [CPUStrapReading], messageLengthWords: Int,
                crcStored: Int, crcValid: Bool) {
        self.readings = readings
        self.messageLengthWords = messageLengthWords
        self.crcStored = crcStored
        self.crcValid = crcValid
    }
}

/// Reading the MIP table out of a FITC partition's payload.
public enum MIPTableReader {
    /// How far into the first block the CPU message header sits, and where the
    /// message itself begins — the tool's `PMC_SoC_smip` container, then the
    /// `CPU_smip` message at its tail (`Design/ME_STRUCTURES.md`).
    public static let cpuHeaderOffset = 0x48
    public static let cpuMessageOffset = 0x4C
    private static let fitcHeaderSize = 4

    /// The CPU straps the payload's MIP table holds, or nil where it has none.
    ///
    /// A record is taken as the MIP table only when its whole content is the
    /// table: `NumberOfDescriptors` blocks at contiguous offsets from the end
    /// of the header to the record's own last byte, with types 1…4 and no
    /// reserved field. A record that merely starts with plausible small
    /// numbers is not one.
    public static func cpuStraps(in payload: Data, map: CPUStrapMap) -> CPUStrapReadings? {
        guard let table = mipTable(in: payload), let first = table.blocks.first,
              first.type == 1,
              first.offset + cpuMessageOffset + 4 <= payload.count else { return nil }
        let base = first.offset
        let header = readUInt32(payload, at: base + cpuHeaderOffset)
        let lengthWords = Int((header >> 24) & 0xFF)
        guard (1...16).contains(lengthWords) else { return nil }
        let messageAt = base + cpuMessageOffset
        let messageBytes = lengthWords * 4
        guard messageAt + messageBytes <= first.offset + first.length,
              messageAt + messageBytes <= payload.count else { return nil }
        let message = payload.subdata(in: messageAt..<(messageAt + messageBytes))
        // The last word's high half is the CRC-16 (CCITT-FALSE) over the words
        // after the first, with its own field zeroed.
        let stored = Int(readUInt32(message, at: messageBytes - 4) >> 16)
        var checked = message
        checked[messageBytes - 2] = 0
        checked[messageBytes - 1] = 0
        let valid = crc16(checked.subdata(in: 4..<messageBytes)) == stored
        var readings: [CPUStrapReading] = []
        for field in map.fields {
            let at = field.offset
            let touched = (field.bit + field.count + 7) / 8
            guard field.count > 0, field.count <= 32, field.bit >= 0,
                  field.bit + field.count <= 32, touched <= 4,
                  at >= 0, at + touched <= message.count else { continue }
            var word: UInt32 = 0
            for index in 0..<touched {
                word |= UInt32(message[at + index]) << (8 * index)
            }
            let mask: UInt32 = field.count == 32 ? .max : (1 << UInt32(field.count)) - 1
            readings.append(CPUStrapReading(name: field.name,
                                            value: Int(word >> UInt32(field.bit) & mask)))
        }
        guard !readings.isEmpty else { return nil }
        return CPUStrapReadings(readings: readings, messageLengthWords: lengthWords,
                                crcStored: stored, crcValid: valid)
    }

    /// The MIP descriptor record of a FITC payload: its blocks, as offsets into
    /// the payload. Nil where no record is one.
    static func mipTable(in payload: Data) -> (blocks: [(type: Int, offset: Int, length: Int)],
                                              size: Int)? {
        guard payload.count >= fitcHeaderSize + 4 else { return nil }
        let count = Int(readUInt32(payload, at: 0))
        guard count > 0, count <= 4096,
              fitcHeaderSize + count * 12 <= payload.count else { return nil }
        for index in 0..<count {
            let entry = fitcHeaderSize + index * 12
            let offset = Int(readUInt32(payload, at: entry + 4))
            let size = Int(readUInt16(payload, at: entry + 8))
            guard size >= 12, offset >= 0, offset + size <= payload.count else { continue }
            let data = payload.subdata(in: offset..<(offset + size))
            guard let blocks = blocks(ofMIP: data) else { continue }
            return (blocks.map { (type: $0.type, offset: offset + $0.offset,
                                  length: $0.length) }, size)
        }
        return nil
    }

    /// The blocks of a MIP descriptor, whose offsets are relative to its start.
    private static func blocks(ofMIP data: Data) -> [(type: Int, offset: Int, length: Int)]? {
        guard data.count >= 12 else { return nil }
        let count = Int(readUInt16(data, at: 0))
        let size = Int(readUInt16(data, at: 2))
        guard (1...8).contains(count), size == data.count, 4 + count * 8 <= data.count
        else { return nil }
        var blocks: [(type: Int, offset: Int, length: Int)] = []
        var expected = 4 + count * 8
        for index in 0..<count {
            let at = 4 + index * 8
            let type = Int(readUInt16(data, at: at))
            let offset = Int(readUInt16(data, at: at + 2))
            let length = Int(readUInt16(data, at: at + 4))
            let reserved = readUInt16(data, at: at + 6)
            guard (0...4).contains(type), reserved == 0, length > 0,
                  offset == expected, offset + length <= size else { return nil }
            expected += length
            blocks.append((type, offset, length))
        }
        guard expected == size else { return nil }
        return blocks
    }

    /// CRC-16/CCITT-FALSE (poly 0x1021, init 0xFFFF, no reflection) — the
    /// tool's `library.Crc.crc16`, the same function the `$UEP` header uses.
    private static func crc16(_ data: Data) -> Int {
        var crc: UInt16 = 0xFFFF
        for byte in data {
            crc ^= UInt16(byte) << 8
            for _ in 0..<8 {
                crc = (crc & 0x8000) != 0 ? (crc << 1) ^ 0x1021 : crc << 1
            }
        }
        return Int(crc)
    }

    private static func readUInt16(_ data: Data, at index: Int) -> UInt16 {
        UInt16(data[index]) | UInt16(data[index + 1]) << 8
    }

    private static func readUInt32(_ data: Data, at index: Int) -> UInt32 {
        UInt32(data[index])
            | UInt32(data[index + 1]) << 8
            | UInt32(data[index + 2]) << 16
            | UInt32(data[index + 3]) << 24
    }
}
